const english: Record<string, string> = Object.fromEntries(englishEntries);

export function t(language: Language, text: string): string {
  if (language === 'ar') return text;
  return english[text] ?? text;
}

export function formatT(language: Language, text: string, values: Record<string, string | number>): string {
  const translated = t(language, text);
  return translated.replace(/\{(\w+)\}/g, (_match, key: string) => String(values[key] ?? ''));
}
